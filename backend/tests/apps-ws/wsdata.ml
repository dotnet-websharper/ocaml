open WebSharper_JavaScript

(* `open WebSharper_JavaScript` shadows the OCaml `String`; keep it. *)
module String = Stdlib.String

(* [@rpc] over structured data: records, variants, tuples, lists, options.
   Values travel in their OCaml runtime representation, so the codecs below are
   generated by `--emit-server` and exercised natively (scripts/rpc-data.sh). *)

type point = { x : int; y : int }
type shape = Dot | Circle of int | Rect of point * point
type pair = int * string
type tree = Leaf of int | Node of tree * tree

let[@javascript] f x = x + 1

let[@rpc] move (p : point) = Async.return { p with x = p.x + 10 }

let[@rpc] area (s : shape) =
  Async.return
    (match s with
     | Dot -> 0
     | Circle r -> 3 * r * r
     | Rect (a, b) -> (b.x - a.x) * (b.y - a.y))

let[@rpc] swap (t : pair) = Async.return (snd t, fst t)

let[@rpc] total (xs : int list) = Async.return (List.fold_left ( + ) 0 xs)

let[@rpc] or_else (o : int option) = Async.return (match o with Some v -> v + 100 | None -> -1)

let[@rpc] sum_tree (t : tree) =
  Async.return (let rec go = function Leaf n -> n | Node (a, b) -> go a + go b in go t)

let[@rpc] rev (xs : int array) =
  Async.return (Stdlib.Array.of_list (List.rev (Stdlib.Array.to_list xs)))

let () = Console.log (Printf.sprintf "f=%d" (f 41))

(* Client-only round-trip through the *generated proxies* (this non-`Ppat_var`
   binding is dropped from `server.ml`): records, variants, tuples, lists,
   options and arrays cross the wire via the generated type descriptor and the
   runtime marshaller. Sequenced so the driver's stdout is deterministic; the
   driver points the transport at the native server, so the native codecs are on
   the other side. *)
let () =
  let log name s = Console.log (Printf.sprintf "client %s => %s" name s) in
  let ints xs = String.concat "," (List.map string_of_int xs) in
  let ( let* ) m k = Async.bind m k in
  Async.run (fun () -> ())
    (let* p = move { x = 1; y = 2 } in
     log "move" (Printf.sprintf "%d,%d" p.x p.y);
     let* n = area Dot in
     log "area Dot" (string_of_int n);
     let* n = area (Circle 5) in
     log "area Circle" (string_of_int n);
     let* n = area (Rect ({ x = 0; y = 0 }, { x = 3; y = 4 })) in
     log "area Rect" (string_of_int n);
     let* (a, b) = swap (7, "hi") in
     log "swap" (Printf.sprintf "%s,%d" a b);
     let* n = total [ 1; 2; 3 ] in
     log "total" (string_of_int n);
     let* n = or_else (Some 5) in
     log "or_else Some" (string_of_int n);
     let* n = or_else None in
     log "or_else None" (string_of_int n);
     let* n = sum_tree (Node (Leaf 1, Leaf 2)) in
     log "sum_tree" (string_of_int n);
     let* xs = rev [| 1; 2; 3 |] in
     log "rev" (ints (Stdlib.Array.to_list xs));
     Async.return ())
