(* Generate a `.js` shim for an OCaml stdlib unit from its module-block layout.

   Each stdlib unit (`Stdlib`, `Stdlib__Array`, ...) is a normal module block
   addressed by field index. We read `ocamlobjinfo <unit>.cmx` to recover the
   index -> value mapping, then emit a JS module whose numeric fields are filled
   with runtime-backed implementations for the names we support, constants, or a
   throwing stub. The implementation tables live in stdlib_shims_data.ml.

   Usage: gen_stdlib_shim <output.js> [Unit]   (Unit defaults to Stdlib) *)

let read_process cmd =
  let ic = Unix.open_process_in cmd in
  let buf = Buffer.create 4096 in
  (try
     while true do
       Buffer.add_string buf (input_line ic);
       Buffer.add_char buf '\n'
     done
   with End_of_file -> ());
  ignore (Unix.close_process_in ic);
  Buffer.contents buf

let ocaml_where () = String.trim (read_process "ocamlc -where")

let cmx_for unit =
  ocaml_where () ^ (if unit = "Stdlib" then "/stdlib.cmx" else "/stdlib__" ^ unit ^ ".cmx")

let clambda_fields cmx =
  let txt = read_process (Printf.sprintf "ocamlobjinfo %s" (Filename.quote cmx)) in
  let marker = "Clambda approximation:" in
  let idx = Str.search_forward (Str.regexp_string marker) txt 0 + String.length marker in
  let section = String.sub txt idx (String.length txt - idx) in
  let i = String.index section '(' in
  let j = String.rindex section ')' in
  let body = String.sub section (i + 1) (j - i - 1) in
  let parts = ref [] and depth = ref 0 and cur = Buffer.create 64 in
  String.iter
    (fun ch ->
      if ch = '(' then incr depth;
      if ch = ')' then decr depth;
      if ch = ';' && !depth = 0 then (
        parts := Buffer.contents cur :: !parts;
        Buffer.clear cur)
      else Buffer.add_char cur ch)
    body;
  if String.trim (Buffer.contents cur) <> "" then parts := Buffer.contents cur :: !parts;
  let fields = Hashtbl.create 64 in
  let re = Str.regexp "^[ \t]*\\([0-9]+\\):[ \t]*\\(.*\\)$" in
  List.iter
    (fun p ->
      let p = String.concat " " (String.split_on_char '\n' p) |> String.trim in
      if Str.string_match re p 0 then
        Hashtbl.replace fields (int_of_string (Str.matched_group 1 p)) (String.trim (Str.matched_group 2 p)))
    (List.rev !parts);
  fields

(* Match `function <prefix>$<name>_<digits>` strictly from the start of the
   descriptor (mirrors Python `re.match`). *)
let value_name d =
  let n = String.length d in
  if n < 8 || String.sub d 0 8 <> "function" then None
  else
    let i = ref 8 in
    let ws = !i in
    while !i < n && (d.[!i] = ' ' || d.[!i] = '\t' || d.[!i] = '\n') do incr i done;
    if !i = ws then None
    else
      let tok_start = !i in
      let j = ref !i in
      while !j < n && d.[!j] <> ' ' && d.[!j] <> '\t' && d.[!j] <> '\n' do incr j done;
      let token = String.sub d tok_start (!j - tok_start) in
      match (try Some (String.rindex token '$') with Not_found -> None) with
      | None -> None
      | Some dp ->
          let start = dp + 1 in
          let tl = String.length token in
          let k = ref start and found = ref (-1) in
          while !found < 0 && !k < tl - 1 do
            if token.[!k] = '_' && token.[!k + 1] >= '0' && token.[!k + 1] <= '9' then found := !k
            else incr k
          done;
          if !found > start then Some (String.sub token start (!found - start)) else None

(* `const(<num>)` or `const("<tag>"=<num>)` -> Some "<num>" *)
let const_value d =
  let re = Str.regexp "const(\\(\"[^\"]*\"=\\)?\\([-+]?[0-9][0-9.eE+-]*\\))$" in
  if Str.string_match re d 0 then Some (Str.matched_group 2 d) else None

let impl_of_unit = function
  | "Stdlib" -> Stdlib_shims_data.stdlib
  | "Array" -> Stdlib_shims_data.array
  | "String" -> Stdlib_shims_data.string
  | "List" -> Stdlib_shims_data.list
  | "Bytes" -> Stdlib_shims_data.bytes
  | "Hashtbl" -> Stdlib_shims_data.hashtbl
  | "Buffer" -> Stdlib_shims_data.buffer
  | "Printf" -> Stdlib_shims_data.printf
  | "Option" -> Stdlib_shims_data.option
  | "Result" -> Stdlib_shims_data.result
  | "Char" -> Stdlib_shims_data.char
  | "Int" -> Stdlib_shims_data.int
  | "Sys" -> Stdlib_shims_data.sys
  | "Seq" -> Stdlib_shims_data.seq
  | "Float" -> Stdlib_shims_data.float
  | _ -> []

let overrides_of_unit unit =
  try List.assoc unit Stdlib_shims_data.index_overrides with Not_found -> []

let () =
  if Array.length Sys.argv < 2 then (
    prerr_endline "usage: gen_stdlib_shim <output.js> [Unit]";
    exit 2);
  let out_path = Sys.argv.(1) in
  let unit = if Array.length Sys.argv > 2 then Sys.argv.(2) else "Stdlib" in
  let impl = impl_of_unit unit in
  let fields = clambda_fields (cmx_for unit) in
  let n = Hashtbl.fold (fun k _ a -> max a k) fields (-1) + 1 in
  let lines = ref [] in
  let add s = lines := s :: !lines in
  add (Printf.sprintf "// Generated by frontend/bin/gen_stdlib_shim.ml from the OCaml %s layout." unit);
  add "// Do not edit by hand.";
  add "function out(s) {";
  add "  if (typeof process !== 'undefined' && process.stdout) process.stdout.write(String(s));";
  add "  else if (typeof console !== 'undefined') console.log(String(s));";
  add "}";
  add
    "function ap(f, args) { return globalThis.OCamlRuntime ? globalThis.OCamlRuntime.caml_apply(f, args) : f.apply(null, args); }";
  if unit = "Printf" then List.iter add Stdlib_shims_data.printf_helpers;
  if unit = "Seq" || unit = "List" || unit = "Array" then List.iter add Stdlib_shims_data.seq_helpers;
  add "const s = { $tag: 0 };";
  for i = 0 to n - 1 do
    add (Printf.sprintf "s[%d] = function () { throw new Error('%s field %d not implemented'); };" i unit i)
  done;
  let stubs = ref 0 and implemented = ref 0 in
  let keys = Hashtbl.fold (fun k _ a -> k :: a) fields [] |> List.sort compare in
  List.iter
    (fun i ->
      let d = Hashtbl.find fields i in
      match value_name d with
      | Some nm when List.mem_assoc nm impl ->
          add (Printf.sprintf "s[%d] = %s;" i (List.assoc nm impl));
          incr implemented
      | Some _ -> incr stubs
      | None -> (match const_value d with Some cv -> add (Printf.sprintf "s[%d] = %s;" i cv) | None -> ()))
    keys;
  List.iter (fun (i, v) -> add (Printf.sprintf "s[%d] = %s;" i v)) (overrides_of_unit unit);
  add "export default s;";
  let oc = open_out out_path in
  output_string oc (String.concat "\n" (List.rev !lines) ^ "\n");
  close_out oc;
  Printf.printf "wrote %s (%s): %d fields, %d implemented, %d stubs\n" out_path unit n !implemented !stubs
