#!/usr/bin/env bash
# Build a wsocaml app that consumes generated WebSharper bindings from an
# installed opam package or a package lib directory.
#   build-ws-app.sh <binding-lib-dir> <entry.ml> [out-dir]
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
fe="$root/frontend/_build/default/bin/main.exe"
be="$root/backend/bin/Debug/net10.0/WebSharper.OCaml.dll"
ref="$root/backend/bin/Debug/net10.0/WebSharper.JavaScript.dll"
extra_refs="${WS_REFS:-}"
ws_compile="${WS_COMPILE:-0}"
ref_args=(--reference "$ref")
for r in $extra_refs; do ref_args+=(--reference "$r"); done
backend_flags=()
if [ "$ws_compile" = "1" ]; then backend_flags+=(--ws-compile); fi
bindir="$1"
entry="$2"
out="${3:-$root/out}"
mkdir -p "$out"
s="$(ocamlc -where)"

runtime_dir="$(ocamlfind query websharper-runtime 2>/dev/null || opam exec -- ocamlfind query websharper-runtime 2>/dev/null || true)"
runtime_inc=()
if [ -n "$runtime_dir" ]; then runtime_inc=(-I "$runtime_dir"); fi
low_first() { echo "$(echo "${1:0:1}" | tr 'A-Z' 'a-z')${1:1}"; }

# 1) type-check the generated bindings -> .cmi in a scratch dir (never write to
#    the installed package directory)
work="$out/.deps"
mkdir -p "$work"
for f in "$bindir"/*.ml; do
  # skip dune's generated wrapper module (e.g. WebSharper_JavaScript.ml)
  grep -q 'generated by dune' "$f" && continue
  cp "$f" "$work/"
done
(cd "$work" && ocamldep -sort *.ml 2>/dev/null | tr ' ' '\n' | grep -v '^$') > "$work/order.txt"
while IFS= read -r f; do
  [ -n "$f" ] || continue
  (cd "$work" && ocamlc -c -I "$s" "${runtime_inc[@]}" "$f")
done < "$work/order.txt"

# 2) compile the entry to IR to discover required modules
"$fe" --input "$entry" --output "$out/Main.wsir.json" --unit Main -I "$bindir" -I "$work" "${runtime_inc[@]}" -I "$s"

globals="$(python3 -c "import json,sys; print(' '.join(json.load(open(sys.argv[1]))['requiredGlobals']))" "$out/Main.wsir.json")"

# 3) compile each required binding module to JS. Wrapped libraries expose
#    internal units named <Lib>__<Module>; map them back to their source file.
for g in $globals; do
  [ "$g" = "Main" ] && continue
  src=""
  if [ -f "$work/$(low_first "$g").ml" ]; then
    src="$work/$(low_first "$g").ml"
  else
    base="${g##*__}"
    cand="$work/$(low_first "$base").ml"
    [ -f "$cand" ] && src="$cand"
  fi
  if [ -z "$src" ]; then
    # wrapper/alias or stdlib shim: no generated code, provide an empty module
    # (shims overwrite this in step 5)
    printf 'let a = {};\na = { $tag: 0 };\nexport default a;\n' > "$out/$g.js"
    continue
  fi
  "$fe" --input "$src" --output "$out/$g.wsir.json" --unit "$g" -I "$work" "${runtime_inc[@]}" -I "$s"
  dotnet "$be" --ir "$out/$g.wsir.json" --output "$out" "${ref_args[@]}" ${backend_flags[@]+"${backend_flags[@]}"} --compact
done

# 4) compile the entry to JS
dotnet "$be" --ir "$out/Main.wsir.json" --output "$out" "${ref_args[@]}" ${backend_flags[@]+"${backend_flags[@]}"} --compact

# 5) stdlib shims
for shim in "$root"/backend/tests/Stdlib*.js; do
  [ -f "$shim" ] || continue
  cp "$shim" "$out/"
done

printf '{ "type": "module" }\n' > "$out/package.json"
echo "built $out/Main.js"
